INDEX_FILE = "INDEX.md"
README_FILE = "README.md"
SKIPPED_FILES = frozenset({INDEX_FILE, README_FILE})
INDEX_TITLE = "# Knowledge"
MARKER_BEGIN = "<!-- knowledge:index:begin -->"
MARKER_END = "<!-- knowledge:index:end -->"
INDEX_COMMAND = "svod knowledge index"
GENERATED_NOTE = f"Generated by `{INDEX_COMMAND}`; edit the notes, not this table."
FIELD_TITLE = "title"
FIELD_TAGS = "tags"
FIELD_SOURCE = "source"
FIELD_DATE = "date"
FIELD_STATUS = "status"
FIELDS = (FIELD_TITLE, FIELD_TAGS, FIELD_SOURCE, FIELD_DATE, FIELD_STATUS)
STATUS_CURRENT = "current"
STATUS_SUPERSEDED = "superseded"
SETTING_KNOWLEDGE = "knowledge"
PROFILE_CONFIG = "profile_config"
TAG_SEPARATOR = ","
TAGS_JOIN = ", "
HEADING_PREFIX = "#"
HEADING_RE = re.compile(r"^#{1,6}\s+(?P<title>.+?)\s*#*\s*$")
SLUG_RE = re.compile(r"[^\w]+")
SLUG_JOIN = "-"
SLUG_FALLBACK = "note"
DOC_SUFFIX = ".md"
LINK = "[{title}]({path})"
MATCH_LINE = "- {title} ({path}): {lead}"
MATCH_LINE_BARE = "- {title} ({path})"
LINE_SEPARATOR = "\n"
TABLE_SEPARATOR = "|---|---|---|---|---|"
PUBLISH_MARK = "svod-knowledge-publish.json"


def publication_reply(ctx: Context) -> None:
    """Bind the next human event; any subsequent event invalidates that request."""
    from .approval import fresh_human_mark, mark_time
    from .git import common_dir_file
    path = common_dir_file(ctx.root, PUBLISH_MARK, ctx.cache.git)
    if path is None or not path.is_file():
        return
    request = json.loads(path.read_text(encoding=ENCODING))
    mark = fresh_human_mark(ctx.root, ctx.config.approval_window, run=ctx.cache.git)
    if mark and "at" in request:
        left = mark_time(mark)
        if left is not None and left > dt.datetime.fromisoformat(request["at"]):
            if "reply" not in request:
                request["reply"] = mark
            elif mark != request["reply"]:
                request["invalidated"] = True
            path.write_text(json.dumps(request), encoding=ENCODING)


def publish(runtime: Runtime, ctx: Context, query: str) -> tuple[bool, str]:
    """Display an exact snapshot, then publish/close only after its next human go-ahead."""
    from .approval import HUMAN_GO, HUMAN_SHA, is_fresh, now, read_human_mark
    from .git import common_dir_file
    from .identity import approver
    from .questions import prompt_sha

    found = resolve(ctx, runtime.pipelines, query)
    matches = {(p.name, s.id): s for p, s in found.matches if s.exists}
    if found.ambiguous or len(matches) != 1:
        raise ValueError("Name exactly one research record")
    (pipeline, source), subject = next(iter(matches.items()))
    if pipeline != "research" or subject.path is None:
        raise ValueError("Publication requires a research record")
    card = safe_path(ctx.root, str(subject.path / "card.md"))
    fields = dict(read_frontmatter(card) or {})
    if fields.get("outcome") != "knowledge":
        raise ValueError("Research outcome must be knowledge")
    findings = safe_path(ctx.root, str(subject.path / "findings.md"))
    body = findings.read_bytes().decode(ENCODING)
    if not body.strip():
        raise ValueError("Research findings must not be empty")
    directory = runtime.config.knowledge_dir
    title = first_heading(split_document(card.read_text(encoding=ENCODING))[1]) or card.parent.name
    target = safe_path(ctx.root, f"{directory}/{slug(card.parent.name)}.md", directory)
    index = safe_path(ctx.root, f"{directory}/{INDEX_FILE}", directory)
    snapshot = {"source": source, "body": body, "title": title,
                "tags": list(tag_list(fields.get("tags"))),
                "target": target.relative_to(ctx.root).as_posix()}
    digest = prompt_sha(json.dumps(snapshot, sort_keys=True, ensure_ascii=False))
    mark_path = common_dir_file(ctx.root, PUBLISH_MARK)
    if mark_path is None:
        raise ValueError("Publication consent requires a git store")
    request = json.loads(mark_path.read_text(encoding=ENCODING)) if mark_path.is_file() else {}
    transactions = request.get("transactions", {})
    transaction = transactions.get(digest, {})
    existing = read_frontmatter(target) if target.is_file() else None
    if target.exists():
        if not (existing and existing.get("publication_sha") == digest
                and existing.get("source") == source
                and existing.get("title") == title and existing.get("tags") == snapshot["tags"]
                and existing.get("status") in (STATUS_CURRENT, STATUS_SUPERSEDED)
                and split_document(target.read_bytes().decode(ENCODING))[1] == body):
            raise ValueError("Knowledge collision: existing note does not match this publication")
        # Agent-editable note fields are not proof of a native publication.
        if not (transaction.get("source") == source
                and transaction.get("target") == snapshot["target"]
                and transaction.get("prompt_sha") == existing.get("prompt_sha")
                and transaction.get("published_by") == existing.get("published_by")
                and transaction.get("prompt_sha") and transaction.get("published_by")):
            raise ValueError("Knowledge collision: missing native publication transaction")
        if (transaction.get("phase") == "completed" and fields.get("status") == "done"
                and fields.get("knowledge") == snapshot["target"]):
            return True, f"Published {snapshot['target']}; closed {source}"
    if (not target.exists() or transaction.get("phase") == "completed"
            or request.get("invalidated")
            or transaction.get("reply") != read_human_mark(ctx.root)
            or not is_fresh(transaction.get("reply"), ctx.config.approval_window)):
        reply = request.get("reply")
        if not (request.get("sha") == digest and not request.get("invalidated")
                and isinstance(reply, dict) and reply == read_human_mark(ctx.root)
                and reply.get(HUMAN_GO) is True
                and is_fresh(reply, ctx.config.approval_window)):
            mark_path.write_text(json.dumps({"sha": digest, "at": now().isoformat(),
                                             "transactions": transactions}), encoding=ENCODING)
            return False, (f"Publish {source} to {snapshot['target']} and close research?\n"
                           f"Snapshot {digest}\n{body}\nReply with a configured go-ahead, "
                           "then repeat this command.")
        who = approver(ctx)
        if who is None:
            raise ValueError("Publication requires a known approver")
        note_fields = {"title": title, "tags": snapshot["tags"], "source": source,
                       "date": today(), "status": STATUS_CURRENT, "published_by": who,
                       "prompt_sha": reply[HUMAN_SHA], "publication_sha": digest}
        transaction = {"source": source, "target": snapshot["target"],
                       "prompt_sha": existing["prompt_sha"] if existing else reply[HUMAN_SHA],
                       "published_by": existing["published_by"] if existing else who,
                       "reply": reply, "phase": "publishing"}
        transactions[digest] = transaction
        request["transactions"] = transactions
        mark_path.write_text(json.dumps(request), encoding=ENCODING)
        if not target.exists():
            write_new(target, f"{OPENING}{dump_yaml(note_fields)}{CLOSING.lstrip()}{body}")
    # Index failure must not close the source. Both paths were validated before any write.
    assert index.name == INDEX_FILE
    write_index(ctx.root, directory)
    fields.update(knowledge=snapshot["target"], status="done")
    _, card_body = split_document(card.read_text(encoding=ENCODING))
    card.write_text(f"{OPENING}{dump_yaml(fields)}{CLOSING.lstrip()}{card_body}", encoding=ENCODING)
    transaction["phase"] = "completed"
    transactions[digest] = transaction
    mark_path.write_text(json.dumps({"transactions": transactions}), encoding=ENCODING)
    return True, f"Published {snapshot['target']}; closed {source}"


@dataclass(frozen=True)
class Entry:
    """One knowledge note: its file, the path relative to the store root and its fields."""

    path: Path
    rel: str
    title: str
    tags: tuple[str, ...]
    source: str
    date: str
    status: str
    lead: str

    @property
    def current(self) -> bool:
        """Whether the note is in force: status current or no status."""
        return self.status == STATUS_CURRENT


def tag_list(value: Any) -> tuple[str, ...]:
    """Tags of a frontmatter value or a command argument: a list or a comma separated string.

    Tags are stripped and lower-cased; empty ones and repeats are dropped, the order is kept.
    """
    if isinstance(value, str):
        items: Iterable[Any] = value.split(TAG_SEPARATOR)
    elif isinstance(value, (list, tuple, set, frozenset)):
        items = value
    else:
        return ()
    tags = (str(item).strip().casefold() for item in items if item is not None)
    return tuple(dict.fromkeys(tag for tag in tags if tag))


def text_field(value: Any) -> str:
    """A frontmatter value as one line of text; empty for none."""
    return "" if value is None else " ".join(str(value).split())


def split_document(text: str) -> tuple[str | None, str]:
    """(frontmatter text or None, body) of a markdown document."""
    if text.startswith("---\r\n"):
        end = text.find("\r\n---\r\n", 3)
        if end != -1:
            return text[5:end], text[end + 7:]
    if not text.startswith(OPENING):
        return None, text
    end = text.find(CLOSING, len(OPENING) - 1)
    if end == -1:
        return None, text
    return text[len(OPENING):end], text[end + len(CLOSING):]


def first_heading(body: str) -> str | None:
    """Text of the first markdown heading of the body, or None."""
    for line in body.splitlines():
        found = HEADING_RE.match(line.strip())
        if found:
            return found.group("title")
    return None


def lead_line(body: str) -> str:
    """First non-empty line of the body that is not a heading; empty when there is none."""
    for line in body.splitlines():
        line = line.strip()
        if line and not line.startswith(HEADING_PREFIX):
            return line
    return ""


def knowledge_dir(root: str | Path, directory: str = DEFAULT_KNOWLEDGE_DIR) -> Path:
    """Directory of the knowledge notes under the store root."""
    return Path(root) / directory


def read_entry(root: Path, path: Path) -> Entry | None:
    """Entry of one note; None when unreadable or its frontmatter names neither title nor tags."""
    try:
        text = path.read_text(encoding=ENCODING)
    except (OSError, UnicodeDecodeError):
        return None
    _, body = split_document(text)
    fields = read_frontmatter(path) or {}
    if FIELD_TITLE not in fields and FIELD_TAGS not in fields:
        return None
    title = text_field(fields.get(FIELD_TITLE)) or first_heading(body) or path.stem
    try:
        rel = path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        rel = path.as_posix()
    return Entry(path=path, rel=rel, title=title, tags=tag_list(fields.get(FIELD_TAGS)),
                 source=text_field(fields.get(FIELD_SOURCE)),
                 date=text_field(fields.get(FIELD_DATE)),
                 status=text_field(fields.get(FIELD_STATUS)) or STATUS_CURRENT,
                 lead=lead_line(body))


def entries(root: str | Path, directory: str = DEFAULT_KNOWLEDGE_DIR) -> list[Entry]:
    """Every note under the knowledge directory, INDEX.md and README.md skipped; newest first."""
    root = Path(root)
    found = []
    for path in documents(knowledge_dir(root, directory)):
        try:
            safe_path(root, str(path), directory)
        except ValueError:
            continue
        if path.name not in SKIPPED_FILES and (entry := read_entry(root, path)) is not None:
            found.append(entry)
    found.sort(key=lambda e: (e.title.casefold(), e.rel))
    found.sort(key=lambda e: e.date, reverse=True)
    return found


def index_lines(root: str | Path, directory: str = DEFAULT_KNOWLEDGE_DIR) -> list[str]:
    """Lines between the index markers: the generated note and the table of the notes."""
    base = knowledge_dir(root, directory)
    lines = [GENERATED_NOTE, "", row(*FIELDS), TABLE_SEPARATOR]
    for entry in entries(root, directory):
        link = LINK.format(title=entry.title, path=entry.path.relative_to(base).as_posix())
        lines.append(row(cell(link), cell(TAGS_JOIN.join(entry.tags)), cell(entry.source),
                         cell(entry.date), cell(entry.status)))
    return lines


def index_text(root: str | Path, directory: str = DEFAULT_KNOWLEDGE_DIR) -> str:
    """The index table of the notes sorted by date, newest first, with its generated note."""
    return LINE_SEPARATOR.join(index_lines(root, directory))


def marked_span(lines: list[str]) -> tuple[int, int] | None:
    """Line numbers of the begin and end markers of the index, or None without both."""
    stripped = [line.strip() for line in lines]
    if MARKER_BEGIN not in stripped:
        return None
    begin = stripped.index(MARKER_BEGIN)
    if MARKER_END not in stripped[begin + 1:]:
        return None
    return begin, stripped.index(MARKER_END, begin + 1)


def write_index(root: str | Path, directory: str = DEFAULT_KNOWLEDGE_DIR) -> tuple[Path, bool]:
    """Write the index between its markers in knowledge/INDEX.md; return (path, changed).

    A missing file is created with a title; a file without the markers gets them at its end.
    Text outside the markers is never touched.
    """
    path = knowledge_dir(root, directory) / INDEX_FILE
    fresh = index_lines(root, directory)
    if path.is_file():
        old = path.read_text(encoding=ENCODING)
        lines = old.split(LINE_SEPARATOR)
    else:
        old, lines = None, [INDEX_TITLE, ""]
    span = marked_span(lines)
    if span is None:
        while lines and not lines[-1].strip():
            lines.pop()
        lines += ([""] if lines else []) + [MARKER_BEGIN, MARKER_END, ""]
        span = marked_span(lines)
    assert span is not None
    begin, end = span
    text = LINE_SEPARATOR.join(lines[:begin + 1] + fresh + lines[end:])
    if text == old:
        return path, False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding=ENCODING)
    return path, True


def slug(title: str) -> str:
    """File name stem of a title: word characters joined by hyphens, lower-cased."""
    return SLUG_RE.sub(SLUG_JOIN, title.casefold()).strip(SLUG_JOIN + "_") or SLUG_FALLBACK


def today() -> str:
    """Today as an ISO date."""
    return dt.date.today().isoformat()


def note_text(fields: dict[str, Any], body: str) -> str:
    """Markdown of a note: the frontmatter block, then the body."""
    return f"{OPENING}{dump_yaml(fields)}{CLOSING.lstrip()}\n{body}"


def ordered_fields(fields: dict[str, Any]) -> dict[str, Any]:
    """The note fields first in their fixed order, any other field after them."""
    known = {name: fields[name] for name in FIELDS if name in fields}
    return {**known, **{k: v for k, v in fields.items() if k not in known}}


def write_new(path: Path, text: str) -> Path:
    """Write a file that must not exist yet; FileExistsError when it does."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "x", encoding=ENCODING) as fh:
        fh.write(text)
    return path


def add(root: str | Path, path: str | Path, tags: Iterable[str] | str,
        title: str | None = None, source: str | None = None,
        directory: str = DEFAULT_KNOWLEDGE_DIR, date: str | None = None) -> Path:
    """Copy a markdown file into the knowledge directory as a note; return the new path.

    The fields of its own frontmatter win; missing ones come from the arguments: the title from
    the argument, else the first heading, else the file name; the tags given are added to its
    own. The note is named after its title. FileNotFoundError without the file, FileExistsError
    when the note exists.
    """
    source_path = Path(path)
    text = source_path.read_text(encoding=ENCODING)
    head, body = split_document(text)
    own = read_frontmatter(source_path) if head is not None else None
    fields: dict[str, Any] = dict(own or {})
    name = (text_field(fields.get(FIELD_TITLE)) or title or first_heading(body)
            or source_path.stem)
    fields[FIELD_TITLE] = name
    given = tag_list(tags if isinstance(tags, str) else list(tags))
    fields[FIELD_TAGS] = list(dict.fromkeys(tag_list(fields.get(FIELD_TAGS)) + given))
    fields.setdefault(FIELD_SOURCE, source or "")
    fields.setdefault(FIELD_DATE, date or today())
    fields.setdefault(FIELD_STATUS, STATUS_CURRENT)
    target = knowledge_dir(root, directory) / f"{slug(name)}{DOC_SUFFIX}"
    if target.exists():
        raise FileExistsError(errno.EEXIST, os.strerror(errno.EEXIST), str(target))
    if fields == own:
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source_path, target)
        return target
    return write_new(target, note_text(ordered_fields(fields), body.lstrip(LINE_SEPARATOR)))


def note(root: str | Path, text: str, tags: Iterable[str] | str, title: str,
         source: str | None = None, directory: str = DEFAULT_KNOWLEDGE_DIR,
         date: str | None = None) -> Path:
    """Create knowledge/<slug of the title>.md from a text; return its path.

    FileExistsError when the note exists.
    """
    fields = {FIELD_TITLE: title, FIELD_TAGS: list(tag_list(tags)), FIELD_SOURCE: source or "",
              FIELD_DATE: date or today(), FIELD_STATUS: STATUS_CURRENT}
    body = f"{HEADING_PREFIX} {title}\n\n{text.strip()}\n"
    target = knowledge_dir(root, directory) / f"{slug(title)}{DOC_SUFFIX}"
    return write_new(target, note_text(fields, body))


def match_line(entry: Entry) -> str:
    """Line of one note for the agent: title, path and its first line."""
    if entry.lead:
        return MATCH_LINE.format(title=entry.title, path=entry.rel, lead=entry.lead)
    return MATCH_LINE_BARE.format(title=entry.title, path=entry.rel)


def supersede(root: Path, old: str, new: str,
              directory: str = DEFAULT_KNOWLEDGE_DIR) -> None:
    """Retire a note without changing either body or the replacement."""
    path = safe_note(root, old, directory)
    replacement = safe_note(root, new, directory)
    safe_path(root, f"{directory}/{INDEX_FILE}", directory)
    seen = {path}
    cursor = replacement
    while True:
        if cursor in seen:
            raise ValueError("Knowledge supersession cycle or self-link")
        seen.add(cursor)
        link = (read_frontmatter(cursor) or {}).get("superseded_by")
        if not link:
            break
        cursor = safe_note(root, str(link), directory)
    fields = dict(read_frontmatter(path) or {})
    rel = replacement.relative_to(root.resolve()).as_posix()
    if fields.get("superseded_by") not in (None, rel):
        raise ValueError("Note already has a different replacement")
    fields.update(status=STATUS_SUPERSEDED, superseded_by=rel)
    _, body = split_document(path.read_bytes().decode(ENCODING))
    path.write_text(f"{OPENING}{dump_yaml(fields)}{CLOSING.lstrip()}{body}", encoding=ENCODING)
    write_index(root, directory)


def safe_path(root: Path, raw: str, directory: str = ".") -> Path:
    """Resolve an instance-local path, refusing escapes and symlink components."""
    root = root.resolve()
    base = root / directory
    path = root / raw
    for candidate in (base, path):
        if not candidate.is_relative_to(root):
            raise ValueError(f"Path outside instance: {candidate}")
        relative = candidate.relative_to(root)
        if ".." in relative.parts or any((root / Path(*relative.parts[:i])).is_symlink()
                                         for i in range(1, len(relative.parts) + 1)):
            raise ValueError(f"Unsafe knowledge path: {candidate}")
    if not path.resolve().is_relative_to(base.resolve()):
        raise ValueError(f"Path outside configured directory: {path}")
    return path.resolve()


def safe_note(root: Path, raw: str, directory: str) -> Path:
    """A real markdown note in the configured knowledge directory."""
    path = safe_path(root, raw, directory)
    if (path.name in SKIPPED_FILES or path.suffix != DOC_SUFFIX
            or read_entry(root, path) is None):
        raise ValueError(f"Not a knowledge note: {raw}")
    return path


def matching(root: str | Path, tags: Iterable[str] | str,
             limit_lines: int = DEFAULT_KNOWLEDGE_LIMIT,
             directory: str = DEFAULT_KNOWLEDGE_DIR) -> list[str]:
    """Lines of the current notes sharing a tag with the given ones, at most limit_lines.

    Each line is "- <title> (<path>): <first non-empty line of the body>"; newest first.
    """
    wanted = set(tag_list(tags if isinstance(tags, str) else list(tags)))
    if not wanted or limit_lines < 1:
        return []
    found = [match_line(e) for e in entries(root, directory)
             if e.current and wanted & set(e.tags)]
    return found[:limit_lines]


def edit_context(runtime: Runtime, ctx: Context, event: dict[str, Any],
                 tool: str, data: dict[str, Any]) -> list[str]:
    """Match only explicit instance-relative edit globs; never infer tags from content."""
    from .hooks.protocol import EDIT_TOOLS, PATCH_TOOL, command_of, event_cwd
    if not runtime.config.knowledge_on_edit or not enabled(runtime):
        return []
    raw = []
    if tool in EDIT_TOOLS:
        raw = [data.get("file_path") or data.get("notebook_path")]
    elif tool == PATCH_TOOL:
        raw = re.findall(r"^\*\*\* (?:Add File|Update File|Delete File|Move to): (.+)$",
                         command_of(data), re.MULTILINE)
    tags = []
    for value in raw:
        if not isinstance(value, str):
            continue
        path = Path(value).expanduser()
        path = path if path.is_absolute() else event_cwd(event) / path
        try:
            path = safe_path(ctx.root, str(path))
        except ValueError:
            continue
        rel = path.relative_to(ctx.root).as_posix()
        tags += [tag for pattern, values in runtime.config.knowledge_file_tags.items()
                 if fnmatchcase(rel, pattern) for tag in values]
    lines = matching(ctx.root, tags, runtime.config.knowledge_limit, runtime.config.knowledge_dir)
    return [runtime.locale.text(HOOK_KNOWLEDGE_HEAD), *lines] if lines else []


def enabled(runtime: Runtime) -> bool:
    """Whether profile_config.agent_context.knowledge is on; on unless set to false."""
    profile = getattr(runtime.config, PROFILE_CONFIG, {})
    settings = profile.get(AGENT_CONTEXT, {}) if isinstance(profile, dict) else {}
    return not (isinstance(settings, dict) and settings.get(SETTING_KNOWLEDGE) is False)


def subject_tags(subject: Subject) -> tuple[str, ...]:
    """Tags in the frontmatter of a subject."""
    frontmatter = subject.attrs.get(ATTR_FRONTMATTER) or {}
    return tag_list(frontmatter.get(FIELD_TAGS)) if isinstance(frontmatter, dict) else ()


def open_subjects(runtime: Runtime, ctx: Context) -> list[Subject]:
    """Existing, not archived subjects of the pipelines that show in the active summary."""
    return [subject for pipeline in runtime.pipelines if pipeline.active
            for subject in pipeline.subject.impl.enumerate(ctx)
            if subject.exists and not subject.archived]


def named_subjects(runtime: Runtime, ctx: Context, named: Iterable[str]) -> list[Subject]:
    """Existing subjects the queries resolve to without ambiguity."""
    found = []
    for query in named:
        resolution = resolve(ctx, runtime.pipelines, query)
        if not resolution.ambiguous:
            found += [subject for _, subject in resolution.matches if subject.exists]
    return found


def knowledge_context(runtime: Runtime, ctx: Context,
                      named: Callable[[], Iterable[str]] | None = None,
                      gap: bool = False) -> list[str]:
    """Context block of the notes matching the tags of the work at hand, as a list of texts.

    named None: the open subjects of the active summary (session start); else a function giving
    the queries of a prompt, called only when the knowledge context is on, whose subjects count.
    Empty when agent_context.knowledge is false, when the subjects have no tags or no current
    note shares one. gap puts an empty line before the block.
    """
    if not enabled(runtime):
        return []
    subjects = (open_subjects(runtime, ctx) if named is None
                else named_subjects(runtime, ctx, named()))
    tags = [tag for subject in subjects for tag in subject_tags(subject)]
    lines = matching(ctx.root, tags, runtime.config.knowledge_limit, runtime.config.knowledge_dir)
    if not lines:
        return []
    block = LINE_SEPARATOR.join([runtime.locale.text(HOOK_KNOWLEDGE_HEAD), *lines])
    return ["", block] if gap else [block]
